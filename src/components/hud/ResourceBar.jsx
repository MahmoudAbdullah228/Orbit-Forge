'use client';

import React from 'react';
import Tooltip from '../ui/Tooltip';

const RESOURCE_META = {
  budget: {
    label: 'BUDGET',
    unit: '$M',
    color: '#FFE45C',
    icon: '💰',
    why: 'Total capital available for launch, spacecraft bus, and science instruments.'
  },
  mass: {
    label: 'MASS',
    unit: 'kg',
    color: '#B9C2D6',
    icon: '⚖️',
    why: 'Spacecraft mass must not exceed launch vehicle payload capacity to destination orbit.'
  },
  power: {
    label: 'POWER',
    unit: 'W',
    color: '#FF9A1F',
    icon: '⚡',
    why: 'Solar wings or RTG must generate sufficient wattage to run instruments and computers.'
  },
  data: {
    label: 'DATA',
    unit: 'Gb',
    color: '#2EE6A8',
    icon: '📡',
    why: 'Scientific measurements generated by payload sensors waiting to be downlinked.'
  },
  communication: {
    label: 'COMMS',
    unit: '%',
    color: '#12A8E8',
    icon: '📶',
    why: 'Antenna gain and ground station line-of-sight required to transmit telemetry to Earth.'
  },
  time: {
    label: 'LIFETIME',
    unit: 'mo',
    color: '#E85BB5',
    icon: '⏳',
    why: 'Operational design life before radiation or fuel depletion ends the mission.'
  }
};

/**
 * ResourceBar - 8-bit segmented battery-style gauge
 */
export default function ResourceBar({
  resourceKey,
  current = 0,
  max = 100,
  customLabel,
  customUnit,
  customWhy,
  segmentsCount = 12,
  inverted = false, // If true, higher is dangerous (e.g. Mass or Cost usage)
  compact = false
}) {
  const meta = RESOURCE_META[resourceKey] || {
    label: customLabel || resourceKey.toUpperCase(),
    unit: customUnit || '',
    color: '#FFB23E',
    icon: '🔹',
    why: customWhy || 'Mission subsystem parameter.'
  };

  const ratio = max > 0 ? Math.min(1.5, Math.max(0, current / max)) : 0;
  const percentage = Math.round(ratio * 100);

  // Status checks
  let statusColor = meta.color;
  let isDanger = false;
  let isWarning = false;

  if (inverted) {
    if (ratio >= 1.0) {
      statusColor = '#FF3B4E'; // Danger
      isDanger = true;
    } else if (ratio >= 0.8) {
      statusColor = '#FFC83D'; // Warning
      isWarning = true;
    }
  } else {
    // Depletion model (like power or budget dropping to zero)
    if (ratio <= 0.15) {
      statusColor = '#FF3B4E';
      isDanger = true;
    } else if (ratio <= 0.3) {
      statusColor = '#FFC83D';
      isWarning = true;
    }
  }

  const filledSegments = Math.min(segmentsCount, Math.round(ratio * segmentsCount));

  if (compact) {
    return (
      <div className="flex flex-col gap-0.5 w-full" aria-label={`${meta.label}: ${current} of ${max} ${meta.unit}`}>
        <div className="flex items-center justify-between text-[9px] font-small leading-none">
          <Tooltip text={meta.why} position="bottom">
            <div className="flex items-center gap-1 cursor-help text-hud-cream hover:text-hud-amber">
              <span className="text-[10px]">{meta.icon}</span>
              <span className="font-bold uppercase tracking-wider">{customLabel || meta.label}</span>
            </div>
          </Tooltip>
          <div className="font-display text-[9px] text-hud-amber">
            <span>{Math.round(current)}</span>
            <span className="text-hull-steel">/{max}{meta.unit}</span>
          </div>
        </div>

        {/* Compact Segmented bar */}
        <div className={`h-2.5 bg-space-void border border-panel-border p-[1px] flex gap-[1px] ${isDanger ? 'animate-pulse' : ''}`}>
          {Array.from({ length: segmentsCount }).map((_, i) => {
            const isFilled = i < filledSegments;
            return (
              <div
                key={i}
                className="flex-1 h-full transition-colors duration-150"
                style={{
                  backgroundColor: isFilled ? statusColor : '#120A3D',
                  boxShadow: isFilled ? 'inset 0 0 0 1px rgba(255,255,255,0.2)' : 'none'
                }}
              />
            );
          })}
        </div>
      </div>
    );
  }

  return (
    <div className="flex flex-col gap-1 w-full" aria-label={`${meta.label}: ${current} of ${max} ${meta.unit}`}>
      <div className="flex items-center justify-between text-[11px] font-small">
        <Tooltip text={meta.why} position="top">
          <div className="flex items-center gap-1.5 cursor-help text-hud-cream hover:text-hud-amber">
            <span>{meta.icon}</span>
            <span className="font-bold">{customLabel || meta.label}</span>
            <span className="text-hud-amber text-[9px] underline">WHY?</span>
          </div>
        </Tooltip>
        <div className="font-display text-[11px] text-hud-amber">
          <span>{Math.round(current)}</span>
          <span className="text-hull-steel font-body text-[16px]"> / {max}{meta.unit}</span>
        </div>
      </div>

      {/* Segmented bar */}
      <div className={`h-4 bg-space-void border-2 border-panel-border p-[2px] flex gap-[2px] ${isDanger ? 'animate-pulse' : ''}`}>
        {Array.from({ length: segmentsCount }).map((_, i) => {
          const isFilled = i < filledSegments;
          return (
            <div
              key={i}
              className="flex-1 h-full transition-colors duration-150"
              style={{
                backgroundColor: isFilled ? statusColor : '#120A3D',
                boxShadow: isFilled ? `inset 0 0 0 1px rgba(255,255,255,0.2)` : 'none'
              }}
            />
          );
        })}
      </div>
    </div>
  );
}
